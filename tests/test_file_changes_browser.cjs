'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const { chromium } = require('../frontend/node_modules/playwright');
(async () => {
  const browser = await chromium.launch({ args: ['--no-sandbox'], executablePath: process.env.CHROMIUM_EXECUTABLE });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    const errors = [], writes = [];
    page.on('pageerror', e => errors.push(e.message));
    page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
    let conflict = true;
    await page.route('**/api/native/call', async route => {
      const call = route.request().postDataJSON();
      if (call.method !== 'command/exec' || call.params.command[0] !== 'python3') return route.continue();
      writes.push(call);
      return route.fulfill({ json: conflict
        ? { exitCode: 1, stdout: '', stderr: '文件在本轮结束后又有修改，未撤销任何变更。' }
        : { exitCode: 0, stdout: JSON.stringify({undone: true, files: 2}), stderr: '' } });
    });
    const shot = async name => {
      if (!process.env.CONSOLE_SCREENSHOTS) return;
      fs.mkdirSync(process.env.CONSOLE_SCREENSHOTS, {recursive: true});
      await page.screenshot({path: `${process.env.CONSOLE_SCREENSHOTS}/${name}.png`});
    };
    await page.goto(process.env.CONSOLE_TEST_URL);
    await page.locator('#text').fill('changes-fixture'); await page.locator('#send').click();
    await page.getByText('正在更新快捷命令与样式。', {exact: true}).waitFor();
    assert.equal(await page.locator('.turn-file-changes').count(), 0, 'running turns have no completion card');
    const card = page.locator('.turn-file-changes');
    await card.getByText('已编辑 2 个文件', {exact: true}).waitFor();
    assert.equal(await card.count(), 1);
    assert.equal(await card.locator('.change-card-summary .change-counts').innerText(), '+6\n-3');
    assert.equal(await card.locator('.change-file-row').count(), 2);
    await page.locator('#text').fill('保留草稿');
    await shot('changes-card');
    await card.locator('.change-file-row').first().click();
    const preview = page.getByRole('dialog', {name: '文件变更预览', exact: true});
    await preview.waitFor();
    assert.deepEqual(await preview.locator('[data-change="add"] .change-line-number').allTextContents(), ['24','37','45','46']);
    assert.equal(await preview.locator('.hljs-keyword').count() > 0, true);
    await shot('changes-preview');
    await page.keyboard.press('Escape');
    await preview.waitFor({state: 'hidden'});
    await card.getByRole('button', {name: '查看变更', exact: true}).click();
    const all = page.getByRole('dialog', {name: '本轮文件变更', exact: true});
    await all.waitFor();
    assert.equal(await all.locator('.changes-dialog-files > section').count(), 2);
    await shot('changes-all'); await page.keyboard.press('Escape');
    await card.getByRole('button', {name: '撤销', exact: true}).click();
    const undo = page.getByRole('dialog', {name: '撤销本轮文件变更？', exact: true});
    await undo.getByRole('button', {name: '撤销文件变更', exact: true}).click();
    await undo.getByRole('alert').getByText(/又有修改/).waitFor();
    assert.equal(await card.getByText('已编辑 2 个文件', {exact: true}).count(), 1);
    conflict = false;
    await undo.getByRole('button', {name: '撤销文件变更', exact: true}).click();
    await undo.waitFor({state: 'hidden'});
    await card.getByText('已撤销 2 个文件的变更', {exact: true}).waitFor();
    assert.equal(writes.length, 2);
    assert.equal(writes[0].params.cwd, '/fixture');
    assert.equal(writes[0].params.command[1], '-c');
    assert.match(writes[0].params.command[3], /^diff --git/);
    assert.equal(await page.locator('#text').inputValue(), '保留草稿');
    await page.reload();
    await card.getByText('已撤销 2 个文件的变更', {exact: true}).waitFor();
    assert.equal(await card.count(), 1, 'replay does not duplicate the summary');
    await page.locator('#text').fill('changes-fixture'); await page.locator('#send').click();
    await page.waitForFunction(() => document.querySelectorAll('.turn-file-changes').length === 2);
    const newest = card.last();
    await newest.getByRole('button', {name: '查看 frontend/src/composer-commands.tsx 的变更', exact: true}).focus();
    await page.keyboard.press('Enter'); await preview.waitFor(); await page.keyboard.press('Escape');
    await page.getByRole('button', {name: '切换深色主题', exact: true}).click();
    await newest.locator('.change-file-row').first().click(); await preview.waitFor();
    await shot('changes-dark'); await page.keyboard.press('Escape');
    await page.setViewportSize({width: 390, height: 844});
    await newest.scrollIntoViewIfNeeded();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await shot('changes-mobile');
    await newest.locator('.change-file-row').first().click(); await preview.waitFor();
    const box = await preview.boundingBox();
    assert.ok(box.x >= 0 && box.x + box.width <= 390);
    await shot('changes-mobile-preview'); await page.keyboard.press('Escape');
    await page.locator('#text').fill('changes-failed-fixture'); await page.locator('#send').click();
    await page.waitForFunction(() => document.querySelectorAll('.turn-file-changes').length === 3);
    assert.equal(await card.last().getByText('已编辑 2 个文件', {exact: true}).count(), 1, 'failed turns retain applied changes');
    await page.locator('#text').fill('no changes'); await page.locator('#send').click();
    await page.getByText('你好，完整回复。', {exact: true}).waitFor();
    assert.equal(await card.count(), 3, 'no empty card for turns without edits');
    assert.deepEqual(errors, []);
    console.log('File change cards: lifecycle, counts, line numbers, preview, keyboard, reload, isolation, undo/conflict, dark and mobile passed.');
  } finally { await browser.close(); }
})().catch(e => {console.error(e); process.exitCode = 1;});
