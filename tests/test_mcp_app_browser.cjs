'use strict';
const assert = require('node:assert/strict');
const { chromium } = require('../frontend/node_modules/playwright');
(async () => {
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_EXECUTABLE, args: ['--no-sandbox'] });
  try {
    const page = await browser.newPage(); const calls = []; const errors = []; const appCalls = [];
    page.on('request', request => { if (/\/api\/mcp-app\/(context|messages)$/.test(request.url())) appCalls.push(request.postDataJSON()); });
    page.on('pageerror', (error) => errors.push(error.message));
    page.on('request', (request) => { if (request.url().endsWith('/api/native/call')) calls.push(request.postDataJSON()); });
    await page.goto(process.env.CONSOLE_TEST_URL);
    await page.locator('#text').fill('mcp-app-fixture'); await page.locator('#send').click();
    // Completion folds the activity. Open it after the reply settles, so lazy
    // App loading cannot race the automatic collapse while clicking a tool.
    await page.locator('[data-final="true"]').getByText('你好，完整回复。', { exact: true }).waitFor();
    const activity = page.locator('[data-activity]').filter({ hasText: 'fixture-app' });
    const app = page.frameLocator('iframe[title="fixture-app 交互视图"]');
    await app.locator('#status').getByText('MCP App ready', { exact: true }).waitFor();
    const iframe = page.locator('iframe[title="fixture-app 交互视图"]');
    assert.equal(await iframe.getAttribute('sandbox'), 'allow-scripts');
    const frame = await (await iframe.elementHandle()).contentFrame();
    assert.equal(await frame.evaluate(() => { try { return !!parent.document; } catch { return false; } }), false);
    const request = page.waitForRequest(r => r.url().endsWith('/api/native/call') && r.postDataJSON().method === 'mcpServer/tool/call');
    // The transcript can still scroll as its activity expands. Keyboard
    // activation keeps this cross-frame action independent of moving coordinates.
    await app.getByRole('button', { name: 'Read tool', exact: true }).press('Enter');
    assert.equal((await request).postDataJSON().params.server, 'fixture-app');
    await app.getByText('native app tool result', { exact: true }).waitFor();
    await app.getByRole('button', { name: 'Change tool', exact: true }).press('Enter');
    await page.getByText('应用请求执行 change', { exact: true }).waitFor();
    assert.equal(calls.filter(c => c.method === 'mcpServer/tool/call' && c.params.tool === 'change').length, 0);
    await page.getByRole('button', { name: '拒绝', exact: true }).click();
    await app.getByText('用户未允许此操作', { exact: true }).waitFor();
    await app.getByRole('button', { name: 'Change tool', exact: true }).press('Enter');
    await page.getByRole('button', { name: '允许本次', exact: true }).click();
    await app.getByText('native app tool result', { exact: true }).waitFor();
    assert.equal(calls.filter(c => c.method === 'mcpServer/tool/call' && c.params.tool === 'change').length, 1);
    const initialization = await frame.evaluate(() => window.initialization);
    assert.deepEqual(initialization.hostCapabilities.message, { text: {}, image: {}, audio: {} });
    assert.deepEqual(initialization.hostCapabilities.updateModelContext, { text: {}, structuredContent: {} });
    assert.equal(initialization.hostCapabilities.sampling, undefined);
    assert.deepEqual(initialization.hostContext.availableDisplayModes, ['inline', 'fullscreen', 'pip']);
    assert.ok(initialization.hostContext.timeZone);
    assert.equal(await frame.evaluate(() => window.notifications.filter(n => n.method === 'ui/notifications/tool-input').length), 1);
    assert.equal(await frame.evaluate(() => window.notifications.filter(n => n.method === 'ui/notifications/tool-result').length), 1);
    const listed = await frame.evaluate(() => rpc('tools/list'));
    assert.ok(listed.tools.some(t => t.name === 'lookup'));
    assert.ok(!listed.tools.some(t => t.name === 'model_only'));
    const inventoryBefore = calls.filter(c => c.method === 'mcpServerStatus/list').length;
    await frame.evaluate(() => Promise.all(Array.from({ length: 20 }, () => rpc('tools/list'))));
    assert.ok(calls.filter(c => c.method === 'mcpServerStatus/list').length - inventoryBefore <= 1,
      'concurrent App inventory reads must share one cached request');
    const forbidden = await frame.evaluate(() => rpc('tools/call', {name: 'model_only'}).then(() => '', e => e.message));
    assert.match(forbidden, /不能调用/);
    assert.equal(calls.filter(c => c.method === 'mcpServer/tool/call' && c.params.tool === 'model_only').length, 0);
    await app.locator('#draft').fill('preserve form state');
    await app.locator('#fullscreen').press('Enter');
    await page.waitForFunction(() => document.querySelector('.mcp-app-surface').dataset.mode === 'fullscreen');
    assert.equal(await frame.evaluate(() => window.context.displayMode), 'fullscreen');
    assert.deepEqual(await frame.evaluate(() => window.context.availableDisplayModes), ['inline', 'fullscreen', 'pip']);
    await page.evaluate(() => document.documentElement.classList.add('dark'));
    await frame.waitForFunction(() => window.context.theme === 'dark');
    assert.equal(await frame.evaluate(() => window.context.displayMode), 'fullscreen');
    await page.evaluate(() => document.documentElement.classList.remove('dark'));
    assert.equal(await app.locator('#draft').inputValue(), 'preserve form state');
    assert.equal(await page.locator('.mcp-app-surface').evaluate(e => e.matches(':popover-open')), true);
    await app.locator('#pip').press('Enter');
    await page.waitForFunction(() => document.querySelector('.mcp-app-surface').dataset.mode === 'pip');
    await app.locator('#inline').press('Enter');
    await page.waitForFunction(() => document.querySelector('.mcp-app-surface').dataset.mode === 'inline');
    await page.getByRole('tab', { name: '摘要', exact: true }).click();
    await page.getByRole('tab', { name: 'Apps', exact: true }).click();
    assert.equal(await app.locator('#draft').inputValue(), 'preserve form state');
    const contextReply = page.waitForResponse(r => r.url().endsWith('/api/mcp-app/context'));
    await app.locator('#context').press('Enter');
    const response = await contextReply;
    assert.equal(response.status(), 200, await response.text());
    await page.waitForFunction(() => document.querySelector('.mcp-app-view') !== null);
    await app.locator('#reply').getByText('{}', {exact: true}).waitFor();
    assert.equal(appCalls.filter(c => c.message).length, 0, 'context does not trigger a message');
    assert.equal(appCalls.at(-1).context.structuredContent.runId, 'run-42');
    await app.locator('#download').press('Enter');
    await page.getByText('应用请求下载文件', {exact: true}).waitFor();
    const download = page.waitForEvent('download');
    await page.getByRole('button', {name: '允许本次', exact: true}).click();
    assert.equal((await download).suggestedFilename(), 'report.txt');
    await app.locator('#message').press('Enter');
    await page.getByRole('button', {name: '拒绝', exact: true}).click();
    await app.locator('#reply').getByText('{"isError":true}', {exact: true}).waitFor();
    assert.equal(appCalls.filter(c => c.message).length, 0);
    await app.locator('#message').press('Enter');
    await page.getByRole('button', {name: '发送到此聊天', exact: true}).click();
    await app.locator('#reply').getByText('{}', {exact: true}).waitFor();
    assert.equal(appCalls.filter(c => c.message).length, 1);
    assert.equal(appCalls.at(-1).threadId, calls.find(c => c.method === 'mcpServer/tool/call').params.threadId);
    await page.setViewportSize({width: 390, height: 844});
    await page.getByRole('dialog', {name: 'Apps', exact: true}).frameLocator('iframe').locator('#status').waitFor();
    const box = await page.getByRole('dialog', {name: 'Apps', exact: true}).boundingBox();
    assert.ok(box.x >= 0 && box.x + box.width <= 391);
    assert.ok(box.height <= 844);
    if (process.env.CONSOLE_SCREENSHOTS) {
      require('node:fs').mkdirSync(process.env.CONSOLE_SCREENSHOTS, {recursive: true});
      await page.screenshot({path: process.env.CONSOLE_SCREENSHOTS + '/mcp-app-mobile.png'});
    }
    await page.setViewportSize({width: 1440, height: 1000});
    await app.locator('#status').getByText('MCP App ready', {exact: true}).waitFor();
    await app.locator('#close').press('Enter');
    await page.getByRole('button', {name: '重新打开应用', exact: true}).waitFor();
    assert.deepEqual(appCalls.at(-1).context, {});
    await page.getByRole('button', {name: '重新打开应用', exact: true}).click();
    await app.locator('#status').getByText('MCP App ready', {exact: true}).waitFor();
    await page.locator('#text').fill('/mcp');
    await page.locator('#text').press('Enter');
    await page.getByRole('option', {name: /会话工具与资源/}).click();
    const server = page.locator('[data-mcp="fixture-app"]');
    await server.getByText('工具与资源', {exact: true}).click();
    const tool = server.locator('.integration-tool').filter({has: page.locator('summary').getByText('lookup', {exact: true})});
    await tool.locator('summary').click();
    await tool.getByRole('button', {name: '调用工具', exact: true}).click();
    const manualApp = tool.frameLocator('iframe');
    await manualApp.locator('#status').getByText('native app tool result', {exact: true}).waitFor();
    await manualApp.locator('#draft').fill('first invocation');
    const previousFrame = await tool.locator('iframe').elementHandle();
    await tool.getByRole('button', {name: '调用工具', exact: true}).click();
    // Wait for the second response to replace the previous invocation before
    // inspecting its result; both invocations deliberately return identical text.
    await page.waitForFunction(previous => !previous.isConnected, previousFrame);
    await manualApp.locator('#status').getByText('native app tool result', {exact: true}).waitFor();
    assert.equal(await manualApp.locator('#draft').inputValue(), '');
    assert.deepEqual(errors, []);
    console.log('MCP App handshake, isolation, scoped tools, context, messages, downloads, display modes, state retention, mobile layout and teardown passed.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
