const AssistantMessage: FC = () => {
  const {
    ToolFallback: ToolFallbackComponent = ToolFallback,
    ToolGroup,
    ReasoningGroup,
    TaskGroup: TaskGroupComponent,
  } = useContext(ThreadComponentsContext);
  const groupBy = TaskGroupComponent ? taskAwareGroupBy : messageGroupBy;

  const hasText = useAuiState((s) =>
    s.message.content.some((part) => part.type === "text" && part.text.trim()),
  );
  const meta = useAuiState((s) => s.message.metadata.custom);
  const activity = !!meta?.activity;
  const running = useAuiState((s) => s.message.status?.type === "running");
  const turn = meta?.turn as
    | { status?: string; started_at?: string; completed_at?: string }
    | undefined;
  const [expanded, setExpanded] = useState(running);
  useEffect(() => setExpanded(running), [running]);
  const stateLabel = running
    ? "正在处理"
    : turn?.status === "interrupted"
      ? "已中断"
      : turn?.status === "failed"
        ? "执行失败"
        : "处理过程";
  const elapsed =
    meta?.lastActivity && turn?.started_at && turn.completed_at
      ? Math.max(
          0,
          Math.round(
            (Date.parse(turn.completed_at) - Date.parse(turn.started_at)) /
              1000,
          ),
        )
      : null;

  return (
    <MessagePrimitive.Root
      data-slot="aui_assistant-message-root"
      data-role="assistant"
      data-activity={activity || undefined}
      data-final={!!meta?.final || undefined}
      className="fade-in slide-in-from-bottom-1 animate-in relative min-w-0 duration-150"
    >
      {activity && (
        <button
          type="button"
          className="activity-trigger"
          aria-label={stateLabel}
          aria-expanded={expanded}
          onClick={() => setExpanded(!expanded)}
        >
          <span className={running ? "activity-spinner" : "activity-dot"} />
          <span>
            {elapsed !== null && Number.isFinite(elapsed)
              ? `${turn?.status === "completed" ? "用时" : `${stateLabel} · `}${elapsed >= 60 ? `${Math.floor(elapsed / 60)} 分 ${elapsed % 60} 秒` : `${elapsed} 秒`}`
              : stateLabel}
          </span>
          <span className="activity-count">
            {String(meta?.itemCount || 0)} 项
          </span>
          <ChevronRightIcon className={expanded ? "rotate-90" : ""} />
        </button>
      )}
      <div
        data-slot="aui_assistant-message-content"
        hidden={activity && !expanded}
        className="text-foreground min-w-0 leading-7 [overflow-wrap:anywhere]"
      >
        <MessagePrimitive.GroupedParts groupBy={groupBy}>
          {({ part, children }) => {
            switch (part.type) {
              case "group-chainOfThought":
                return <div data-slot="aui_chain-of-thought">{children}</div>;
              case "group-task":
                return TaskGroupComponent ? (
                  <TaskGroupComponent group={part} />
                ) : null;
              case "group-tool":
                if (activity)
                  return <div className="activity-tools">{children}</div>;
                if (ToolGroup) {
                  return <ToolGroup group={part}>{children}</ToolGroup>;
                }
                return (
                  <ToolGroupRoot variant="ghost">
                    <ToolGroupTrigger
                      count={part.indices.length}
                      active={part.status.type === "running"}
                    />
                    <ToolGroupContent>{children}</ToolGroupContent>
                  </ToolGroupRoot>
                );
              case "group-reasoning": {
                if (ReasoningGroup) {
                  return (
                    <ReasoningGroup group={part}>{children}</ReasoningGroup>
                  );
                }
                const running = part.status.type === "running";
                return (
                  <ReasoningRoot streaming={running} variant="ghost">
                    <ReasoningTrigger
                      active={running}
                      interrupted={part.status.type === "incomplete"}
                      duration={reasoningDuration(part.timing)}
                    />
                    <ReasoningContent aria-busy={running}>
                      <ReasoningText>{children}</ReasoningText>
                    </ReasoningContent>
                  </ReasoningRoot>
                );
              }
              case "text":
                return <MarkdownText />;
              case "reasoning":
                return <Reasoning {...part} />;
              case "tool-call":
                return part.toolUI ?? <ToolFallbackComponent {...part} />;
              case "data":
                return part.dataRendererUI;
              case "file":
                return (
                  <div data-slot="aui_assistant-message-file" className="py-1">
                    <MessageFile {...part} />
                  </div>
                );
              case "image":
                return (
                  <div data-slot="aui_assistant-message-image" className="py-1">
                    <Image {...part} />
                  </div>
                );
              case "indicator":
                return (
                  <span
                    data-slot="aui_assistant-message-indicator"
                    className="animate-pulse font-sans"
                    aria-label="Assistant is working"
                  >
                    {"●"}
                  </span>
                );
              default:
                return null;
            }
          }}
        </MessagePrimitive.GroupedParts>
        <MessageError />
      </div>

      {hasText && !activity && (
        <div
          data-slot="aui_assistant-message-footer"
          className="-ml-2 flex min-h-9 items-center pt-1"
        >
          <BranchPicker />
          <AssistantActionBar />
        </div>
      )}
    </MessagePrimitive.Root>
  );
};

